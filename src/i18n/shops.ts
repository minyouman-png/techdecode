/* ===== 헬퍼 ===== */
export function shopCopy(shop: ShopEntry, lang: Lang): ShopCopy {
  // 번역이 없는 언어는 영어 → 한국어 순으로 폴백한다(빈 페이지를 만들지 않기 위해).
  return shop.copy[lang] ?? shop.copy.en ?? shop.copy.ko;
}
export function shopsIndexUrl(lang: Lang): string {
  return localizeUrl('/shops/', lang);
}
export function shopUrl(slug: string, lang: Lang): string {
  return localizeUrl(`/shops/${slug}/`, lang);
}
export function telHref(tel: string): string {
  return `tel:${tel.replace(/[^0-9+]/g, '')}`;
}
export function newsIndexUrl(lang: Lang): string {
  return localizeUrl('/news/', lang);
}

/** 카드·상세에 쓰는 지역 표기. 예: '강원도 원주' */
export function shopLocation(shop: ShopEntry, lang: Lang): string {
  return `${regionLabel(shop.region, lang)} ${shop.city}`.trim();
}

/** 카드에 쓰는 업종 표기. 세부 표기가 있으면 그걸 우선한다(‘음식점’보다 ‘통닭’이 정보량이 크다). */
export function shopCategoryText(shop: ShopEntry, lang: Lang): string {
  if (lang === 'ko' && shop.categoryDetail) return shop.categoryDetail;
  return categoryLabel(shop.category, lang);
}

/** ⚠️**등록이 0인 지역·업종은 아예 내보내지 않는다.**
 *  업체가 1곳인데 '서울 0곳 / 경기도 0곳' 칸을 보여주면 빈 서랍을 자랑하는 꼴이고,
 *  사장님께 보여줄 때 제일 먼저 눈에 띄는 게 그 빈칸이 된다. 채워진 것만 보여준다. */
export function regionFacets(lang: Lang): { code: RegionCode; label: string; count: number }[] {
  return REGIONS.map((code) => ({
    code,
    label: regionLabel(code, lang),
    count: shops.filter((s) => s.region === code).length,
  })).filter((f) => f.count > 0);
}
export function categoryFacets(lang: Lang): { code: CategoryCode; label: string; count: number }[] {
  return CATEGORIES.map((code) => ({
    code,
    label: categoryLabel(code, lang),
    count: shops.filter((s) => s.category === code).length,
  })).filter((f) => f.count > 0);
}

/** 클라이언트 인스턴트 검색용 색인.
 *  ⚠️구글 CSE 는 **색인되지 않은 신규 업체를 못 찾는다.** 등록 직후부터 검색돼야 하므로
 *  자체 색인이 기본이고 구글은 보조다. 업체 수가 수백 곳이 되기 전까지 이 방식이 더 정확하다. */
export function searchIndex(lang: Lang) {
  return shops.map((shop) => {
    const c = shopCopy(shop, lang);
    const terms = [
      c.name,
      c.tagline,
      shopLocation(shop, lang),
      shop.city,
      regionLabel(shop.region, lang),
      categoryLabel(shop.category, lang),
      shop.categoryDetail ?? '',
      ...c.menu.map((m) => m.name),
    ];
    return {
      slug: shop.slug,
      region: shop.region,
      category: shop.category,
      q: terms.join(' ').toLowerCase(),
    };
  });
}

/** 등록 업체 전체의 소식을 최신순으로 합친다(가게 상세에 흩어져 있는 것을 한 줄기로).
 *  origin: 'press' = menewsoft 가 공개 자료에서 정리(출처 필수) */
export function allShopNews(lang: Lang) {
  const rows = shops.flatMap((shop) => {
    const c = shopCopy(shop, lang);
    return c.news.map((n) => ({
      shop,
      shopName: c.name,
      date: n.date,
      text: n.text,
      source: n.source,
      origin: 'press' as const,
    }));
  });
  return rows.sort((a, b) => (a.date < b.date ? 1 : -1));
}
