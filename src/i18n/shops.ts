/* ===== 데이터 모델 ===== */
export interface MenuItem {
  name: string;
  price: string;
  /** 이 메뉴를 왜 시키는가 — 조리법·재료·식감 근거로. 과장 금지. */
  pride: string;
  /** 처음 온 사람에게 추천하는 순서(1이 가장 먼저) */
  rank?: number;
}
export interface NewsItem {
  date: string;
  text: string;
  /** ⚠️**필수**(타입 강제) — 가게 명의 공지가 아니라 '어디에 이렇게 나와 있다'임을 밝힌다.
   *  출처 없는 소식은 우리가 지어낸 말이 되고, 손님이 그걸 믿고 헛걸음하면 가게가 피해를 본다.
   *  출처를 못 찾으면 **쓰지 않는다**. 그래서 optional 이 아니라 required 다(빠지면 빌드 실패). */
  source: { label: string; url: string };
}
export interface ShopCopy {
  name: string;
  tagline: string;
  /** 히어로 아래 본문(문단 배열) */
  story: string[];
  menu: MenuItem[];
  /** 방문 정보(라벨/값) */
  visit: { label: string; value: string }[];
  /** 가기 전 주의사항 */
  tips: string[];
  news: NewsItem[];
}
export interface ShopEntry {
  slug: string;
  /** 광역 지역 코드(필터 단위) */
  region: RegionCode;
  /** 시·군 — 표시·검색용. 예: '원주' */
  city: string;
  /** 업종 코드(필터 단위) */
  category: CategoryCode;
  /** 업종 세부 표기. 예: '통닭' — 필터에는 안 쓰고 카드·검색어에만 쓴다 */
  categoryDetail?: string;
  since: string;
  /** 확인 날짜 — 가격·영업시간이 언제 기준인지 */
  verified: string;
  cover: string;
  images: string[];
  tel: string;
  mapUrl: string;
  sources: { label: string; url: string }[];
  copy: Partial<Record<Lang, ShopCopy>> & { ko: ShopCopy };
}

