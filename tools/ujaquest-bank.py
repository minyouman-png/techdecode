def Q(qid, q, a, wrong, o):
    """문제 하나. q=화면·음성 문장, a=정답, wrong=오답 보기들, o=정답인 까닭."""
    for w in [a] + wrong:
        if len(w) > MAXLEN:
            raise SystemExit(f'{qid}: 보기 "{w}" 가 {MAXLEN}글자를 넘습니다')
    if len(set([a] + wrong)) != len(wrong) + 1:
        raise SystemExit(f'{qid}: 보기가 겹칩니다 {[a] + wrong}')
    return {'id': qid, 'q': q, 'a': a, 'c': [a] + wrong[:2], 'o': o}


