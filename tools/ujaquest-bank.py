def build(name: str) -> dict:
    cfg = SUBJECTS[name]
    lines, stages = {}, []
    for no, (key, title, concept, probs) in enumerate(cfg['data'], 1):
        jong = (ord(concept[-1]) - 0xAC00) % 28 != 0 if '가' <= concept[-1] <= '힣' else False
        for mode in ('brick', 'mob'):
            for v, do in enumerate(DO[mode]):
                lines[f'intro_{key}_{mode}_{v}'] = (
                    f'이번 동산에서는 {concept}{"을" if jong else "를"} 알아볼 거야. {do}')
        for v, h in enumerate(cfg['hint'][key]):
            lines[f'x_{key}_{v}'] = f'아쉽다, 틀렸어. {h}'
        for p in probs:
            lines[f'q_{p["id"]}'] = p['q']
            lines[f'o_{p["id"]}'] = f'정답이야! {p["o"]}'
        stages.append({'no': no, 'key': key, 'title': title, 'concept': concept,
                       'problems': probs})
    for hero, hname in HEROES.items():
        key = 'c_welcome' if hero == DEFAULT_HERO else f'c_welcome_{hero}'
        lines[key] = cfg['welcome'].format(hero=hname, wa=wa(hname))
    for k, v in COMMON.items():
        lines[f'c_{k}'] = v
    return {'version': 1, 'subject': name,
            'title': cfg['title'].format(hero=HEROES[DEFAULT_HERO]),
            'titles': {h: cfg['title'].format(hero=n) for h, n in HEROES.items()},
            'stages': stages, 'lines': lines, 'variants': 2}


def main() -> int:
    OUTDIR.mkdir(parents=True, exist_ok=True)
    for name in SUBJECTS:
        data = build(name)
        (OUTDIR / f'{name}.json').write_text(json.dumps(data, ensure_ascii=False, indent=1),
                                             encoding='utf-8')
        nq = sum(len(s['problems']) for s in data['stages'])
        print(f"{data['title']}: 동산 {len(data['stages'])} · 문제 {nq} · "
              f"음성 {len(data['lines'])}개 → {name}.json")
        ids = [p['id'] for s in data['stages'] for p in s['problems']]
        if len(set(ids)) != len(ids):
            print('  ⚠️문제 id 중복!', file=sys.stderr)
            return 1
    return 0


