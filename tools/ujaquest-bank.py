def wa(name: str) -> str:
    """'~와/과' — 받침이 있으면 '과', 없으면 '와'. (유자와 / 깨비와)"""
    last = name[-1]
    jong = (ord(last) - 0xAC00) % 28 != 0 if '가' <= last <= '힣' else False
    return '과' if jong else '와'

